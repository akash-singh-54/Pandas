import pandas as pd

print("\n")

# -------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# Create a dataset of 5 students from CodeDesk containing the following columns:
#      @ Student_ID
#      @ Name
#      @ Course
#      @ Fees
#      @ Marks

data = {
    "Student ID" : [101, 102, 103, 104, 105 ], 
    "Name": ["Amit", "Priya", "Rahul", "Neha", "Vikas" ],
    "Course": [ "Python", "Data Analytics", "Python", "Web Development", "Cyber Security" ],
    "Fees": [15000, 25000, 15000, 18000, 25000 ],
    "Marks": [80, 90, 75, 85, 95 ]
}

print(data)

print("\n")

# -------------------------------------------------------------------------------------------------------------------------------------------------------------------------
#Tasks:
# 1. Create the DataFrame.

df = pd.DataFrame(data)
print(df)

print("\n")

# -------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 2. Select only the Name and Course columns.

print(df[["Name", "Course"]])
print("\n")

# -------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 3. Extract the complete record of a single student.

print(df.loc[0])
print("\n")

# -------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 4. Filter students whose fees are greater than ₹20,000.

print(df[df["Fees"] > 20000])
print("\n")

# -------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 5. Filter students whose marks are greater than 80.

print(df[df["Marks"] > 80])
print("\n")

# -------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 6. Filter the data using two combined conditions.

print(df[(df["Fees"] > 20000) & (df["Marks"] >80 )])
print("\n")

# -------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 7. Sort Marks in descending order.

print(df.sort_values("Marks"))
print("\n")

# -------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 8. Extract students enrolled only in the Data Analytics and Python courses.

print(df[(df["Course"] == "Data Analytics") | (df["Course"] == "Python" )])
